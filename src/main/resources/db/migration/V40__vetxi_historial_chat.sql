-- Fase 10: historial de Vetxi separado por usuario y sucursal. UUID de mensaje para reintentos idempotentes.
CREATE TABLE IF NOT EXISTS vetxi_chat_mensaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id VARCHAR(36) NOT NULL,
    conversacion_id VARCHAR(36) NOT NULL,
    usuario_id INTEGER NOT NULL,
    sucursal_id INTEGER NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    es_usuario BOOLEAN NOT NULL,
    texto TEXT NOT NULL,
    sin_ia BOOLEAN DEFAULT false NOT NULL,
    rol_ia VARCHAR(20),
    roles_bloqueados TEXT DEFAULT '[]' NOT NULL,
    fuentes TEXT DEFAULT '[]' NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_vetxi_chat_mensaje UNIQUE (usuario_id, sucursal_id, mensaje_id)
);
CREATE INDEX IF NOT EXISTS idx_vetxi_chat_propietario ON vetxi_chat_mensaje(usuario_id, sucursal_id, id);
CREATE INDEX IF NOT EXISTS idx_vetxi_chat_conversacion ON vetxi_chat_mensaje(usuario_id, sucursal_id, conversacion_id, id);
