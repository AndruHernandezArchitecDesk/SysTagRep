-- Vendex / PostgreSQL: actualización incremental Vetxi + Seguimiento SRI.
-- Ejecutar como propietario de la BD o postgres, con la aplicación detenida.
-- Requiere una instalación Vendex existente con multi-sucursal (V24).
-- No sustituye las migraciones completas V1..V40 de una instalación nueva.
-- Reejecutable: no borra datos, no reinicia consumo, no cambia estados SRI,
-- no crea asociaciones de compatibilidad a partir del texto del inventario.
-- No modifica flyway_schema_history ni ejecuta baseline/repair.
-- psql -X -v ON_ERROR_STOP=1 -h HOST -U postgres -d dbTag -f ESTE_ARCHIVO.sql

BEGIN;
SET LOCAL search_path = public, pg_catalog;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';

-- Abortar antes de cambiar nada si faltan estructuras de la versión anterior.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('usuarios', 'id'), ('sucursal', 'id'), ('cliente', 'id'),
            ('proveedor', 'nombre'), ('inventario', 'id'),
            ('inventario', 'codigo'), ('inventario', 'descripcion'),
            ('inventario', 'cantidad'), ('inventario', 'estado'),
            ('inventario', 'precio_venta'), ('inventario', 'costo_sin_iva'),
            ('inventario', 'proveedor_id'), ('inventario', 'sucursal_id'),
            ('factura_registro', 'sucursal_id'), ('factura_registro', 'estado_sri'),
            ('factura_detalle', 'factura_registro_id'),
            ('nota_venta_registro', 'sucursal_id'),
            ('cuentas_por_cobrar', 'factura_registro_id'),
            ('cuentas_por_cobrar', 'nota_venta_id'),
            ('comprobantes_electronicos', 'clave_acceso'),
            ('comprobantes_electronicos', 'estado_sri')
        ) AS requisitos(tabla, columna)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                       WHERE table_schema='public' AND table_name=r.tabla AND column_name=r.columna) THEN
            RAISE EXCEPTION 'Falta public.%.%: aplicar/revisar las migraciones previas antes de esta actualización.', r.tabla, r.columna;
        END IF;
    END LOOP;
END $$;

-- Consumo y sesiones IA (equivalente a las estructuras de V36).
CREATE TABLE IF NOT EXISTS vendexi_consumo (
    id BIGSERIAL PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT now(),
    modulo VARCHAR(40) NOT NULL,
    operacion VARCHAR(40) NOT NULL,
    modelo VARCHAR(80),
    tokens_entrada BIGINT NOT NULL DEFAULT 0,
    tokens_salida BIGINT NOT NULL DEFAULT 0,
    costo_estimado NUMERIC(12,6) NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_vendexi_consumo_fecha ON vendexi_consumo(fecha);
CREATE TABLE IF NOT EXISTS vendexi_periodo (
    id INT PRIMARY KEY DEFAULT 1,
    inicio TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT vendexi_periodo_unico CHECK (id=1)
);
INSERT INTO vendexi_periodo(id, inicio) VALUES (1, now()) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS vendexi_sesion (
    id BIGSERIAL PRIMARY KEY,
    inicio TIMESTAMP NOT NULL DEFAULT now(),
    fin TIMESTAMP,
    duracion_seg BIGINT,
    modulo VARCHAR(40) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'CONSULTA'
);
CREATE INDEX IF NOT EXISTS idx_vendexi_sesion_inicio ON vendexi_sesion(inicio);

-- Historial de conversaciones (misma estructura que V40).
CREATE TABLE IF NOT EXISTS vetxi_chat_mensaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id VARCHAR(36) NOT NULL,
    conversacion_id VARCHAR(36) NOT NULL,
    usuario_id INTEGER NOT NULL,
    sucursal_id INTEGER NOT NULL,
    titulo VARCHAR(120) NOT NULL,
    es_usuario BOOLEAN NOT NULL,
    texto TEXT NOT NULL,
    sin_ia BOOLEAN DEFAULT false NOT NULL,
    rol_ia VARCHAR(20),
    roles_bloqueados TEXT DEFAULT '[]' NOT NULL,
    fuentes TEXT DEFAULT '[]' NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_vetxi_chat_mensaje UNIQUE(usuario_id, sucursal_id, mensaje_id)
);
CREATE INDEX IF NOT EXISTS idx_vetxi_chat_propietario ON vetxi_chat_mensaje(usuario_id, sucursal_id, id);
CREATE INDEX IF NOT EXISTS idx_vetxi_chat_conversacion ON vetxi_chat_mensaje(usuario_id, sucursal_id, conversacion_id, id);

-- Catálogo estructurado de compatibilidad. No se insertan vehículos de ejemplo
-- ni se infiere compatibilidad de palabras en las descripciones.
CREATE TABLE IF NOT EXISTS vehiculo (
    id SERIAL PRIMARY KEY,
    marca VARCHAR(50) NOT NULL,
    modelo VARCHAR(50) NOT NULL,
    anio_desde INT,
    anio_hasta INT,
    motor VARCHAR(50),
    combustible VARCHAR(20),
    vin_prefijo VARCHAR(8),
    pais_origen VARCHAR(50),
    tipo_vehiculo VARCHAR(30),
    creado_en TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vehiculo_marca_modelo ON vehiculo(marca, modelo);
CREATE INDEX IF NOT EXISTS idx_vehiculo_anio ON vehiculo(anio_desde, anio_hasta);
CREATE INDEX IF NOT EXISTS idx_vehiculo_vin ON vehiculo(vin_prefijo) WHERE vin_prefijo IS NOT NULL;
CREATE TABLE IF NOT EXISTS inventario_vehiculo (
    inventario_id INTEGER NOT NULL REFERENCES inventario(id) ON DELETE CASCADE,
    vehiculo_id INTEGER NOT NULL REFERENCES vehiculo(id) ON DELETE CASCADE,
    notas VARCHAR(200),
    PRIMARY KEY(inventario_id, vehiculo_id)
);
CREATE INDEX IF NOT EXISTS idx_iv_veh_vehiculo ON inventario_vehiculo(vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_iv_veh_inventario ON inventario_vehiculo(inventario_id);

-- Cola SRI: ANULADO cabe en estado VARCHAR(15); no se requiere nueva columna.
-- Se conserva proximo_intento NOT NULL; las tareas anuladas dejan de ser elegibles
-- porque listarParaReintentar solo selecciona estado='PENDIENTE'.
CREATE TABLE IF NOT EXISTS comprobante_pendiente_sri (
    id SERIAL PRIMARY KEY,
    comprobante_id INTEGER REFERENCES comprobantes_electronicos(id),
    tipo_comprobante VARCHAR(20) NOT NULL,
    clave_acceso VARCHAR(49) UNIQUE NOT NULL,
    numero_comprobante VARCHAR(30),
    ambiente VARCHAR(10),
    intentos INTEGER NOT NULL DEFAULT 0,
    ultimo_intento TIMESTAMP,
    proximo_intento TIMESTAMP NOT NULL DEFAULT now(),
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    ultimo_mensaje_sri TEXT
);
CREATE INDEX IF NOT EXISTS idx_pendiente_estado_proximo ON comprobante_pendiente_sri(estado, proximo_intento);
CREATE INDEX IF NOT EXISTS idx_pendiente_clave ON comprobante_pendiente_sri(clave_acceso);

-- Conservar completos los motivos del SRI (V33). No recortar mensajes históricos.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN SELECT * FROM (VALUES
        ('comprobante_pendiente_sri','ultimo_mensaje_sri'),
        ('comprobantes_electronicos','mensaje_sri'), ('factura_registro','mensaje_sri'),
        ('xml_enviados','mensaje_sri'), ('nota_credito_registro','mensaje_sri'),
        ('nota_debito_registro','mensaje_sri'), ('guia_remision_registro','mensaje_sri'),
        ('retencion_registro','mensaje_sri')
    ) AS mensajes(tabla, columna)
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema='public' AND table_name=r.tabla
                     AND column_name=r.columna AND data_type <> 'text') THEN
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I TYPE TEXT', r.tabla, r.columna);
        END IF;
    END LOOP;
END $$;

-- Permisos para el usuario de aplicación si está creado.
DO $$
DECLARE
    tabla TEXT;
    secuencia TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='app_vendex') THEN
        GRANT USAGE ON SCHEMA public TO app_vendex;
        GRANT SELECT, INSERT ON vetxi_chat_mensaje TO app_vendex;
        GRANT SELECT, INSERT, UPDATE ON vendexi_consumo, vendexi_periodo, vendexi_sesion,
            comprobante_pendiente_sri TO app_vendex;
        GRANT SELECT, INSERT, UPDATE, DELETE ON vehiculo TO app_vendex;
        GRANT SELECT, INSERT, DELETE ON inventario_vehiculo TO app_vendex;
        GRANT SELECT, UPDATE ON comprobantes_electronicos TO app_vendex;
        FOREACH tabla IN ARRAY ARRAY['cliente','proveedor','inventario','grupo','marca',
                'factura_registro','factura_detalle','nota_venta_registro','cuentas_por_cobrar']
        LOOP
            IF to_regclass('public.' || tabla) IS NOT NULL THEN
                EXECUTE format('GRANT SELECT ON TABLE public.%I TO app_vendex', tabla);
            END IF;
        END LOOP;
        FOREACH tabla IN ARRAY ARRAY['factura_registro','nota_credito_registro',
                'nota_debito_registro','guia_remision_registro','retencion_registro']
        LOOP
            IF to_regclass('public.' || tabla) IS NOT NULL THEN
                EXECUTE format('GRANT UPDATE ON TABLE public.%I TO app_vendex', tabla);
            END IF;
        END LOOP;
        FOREACH tabla IN ARRAY ARRAY['vetxi_chat_mensaje','vendexi_consumo','vendexi_sesion',
                'vehiculo','comprobante_pendiente_sri']
        LOOP
            secuencia := pg_get_serial_sequence('public.' || tabla, 'id');
            IF secuencia IS NOT NULL THEN
                EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO app_vendex', secuencia);
            END IF;
        END LOOP;
    END IF;
END $$;

COMMIT;

-- Verificación informativa. Deben aparecer las siete tablas esperadas.
SELECT table_name FROM information_schema.tables
WHERE table_schema='public' AND table_name IN (
    'vetxi_chat_mensaje','vendexi_consumo','vendexi_periodo','vendexi_sesion',
    'vehiculo','inventario_vehiculo','comprobante_pendiente_sri'
) ORDER BY table_name;
