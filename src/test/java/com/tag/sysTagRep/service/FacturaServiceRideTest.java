            st.execute("INSERT INTO factura_detalle(id, factura_registro_id, inventario_id, codigo, descripcion, cantidad, precio_unitario, precio_total, subtotal, iva, descuento, total, fecha_registro) VALUES (1, 1, 1, '001', 'Aceite 5W30', 2, 30.00, 60.00, 60.00, 9.00, 0.00, 69.00, CURRENT_TIMESTAMP)");
