            st.execute("INSERT INTO cliente(id, nombre, identificacion, direccion, correo, telefono, celular, fecha_registro, estado) VALUES (1, 'Cliente Prueba', '1790000000002', 'Quito', 'cliente@example.com', '0988888888', '0988888888', CURRENT_TIMESTAMP, TRUE)");
