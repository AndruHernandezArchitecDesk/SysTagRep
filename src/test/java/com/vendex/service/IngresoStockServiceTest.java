    @Test void endpointDeSincronizacionConfirmaPorCodigoEnSucursalAutenticada() throws Exception {
        int id = negativo("API-1", -5, 7); int otro = negativo("API-1", -10, 8);
        var controller = new com.vendex.controller.api.OfflineSyncApiController(null);
        var app = io.javalin.Javalin.create(c -> c.showJavalinBanner = false);
        app.before(ctx -> com.vendex.util.SesionActual.iniciarApi(null, 7, null));
        app.after(ctx -> com.vendex.util.SesionActual.cerrarApi());
        app.post("/ingreso", controller::ingresoMercaderia);
        app.start(0);
        try {
            String body = """
                    {"proveedorId":4,"numeroFactura":"API-F1","formaPago":"Efectivo","sucursalId":8,
                     "productos":[{"codigo":"OTRO-TAG","codigoManual":" api-1 ","descripcion":"Desde API",
                     "costoSinIVA":"10.00","precioVenta":"15.00","cantidad":3}]}
                    """;
            var request = java.net.http.HttpRequest.newBuilder(java.net.URI.create("http://127.0.0.1:" + app.port() + "/ingreso"))
                    .header("Content-Type", "application/json").POST(java.net.http.HttpRequest.BodyPublishers.ofString(body)).build();
            var cliente = java.net.http.HttpClient.newHttpClient();
            var respuesta = cliente.send(request, java.net.http.HttpResponse.BodyHandlers.ofString());
            assertEquals(200, respuesta.statusCode(), respuesta.body());
            assertTrue(respuesta.body().contains("\"inventarioId\":" + id));
            assertEquals(-2, valor("SELECT cantidad FROM inventario WHERE id=" + id));
            assertEquals(-10, valor("SELECT cantidad FROM inventario WHERE id=" + otro));
            assertEquals(400, cliente.send(request, java.net.http.HttpResponse.BodyHandlers.ofString()).statusCode());
            assertEquals(-2, valor("SELECT cantidad FROM inventario WHERE id=" + id));
        } finally { app.stop(); }
    }

    @Test void facturaHistoricaSePuedeReemplazarSinVentasPeroConservaBloqueoSiFueVendida() throws Exception {
        int id = negativo("LEGADO", 4, 7);
        try (Connection con = DatabaseConnection.getConnection(); var st = con.createStatement()) {
            st.executeUpdate("INSERT INTO factura_proveedor(numero_factura,proveedor_id,codigo,codigo_manual,cantidad) "
                    + "VALUES ('ORIGEN',4,'TAG-ORIGEN','LEGADO',4)");
            st.executeUpdate("INSERT INTO factura_detalle VALUES (" + id + ")");
        }
        assertThrows(IllegalStateException.class,
                () -> service.guardar(List.of(compra("LEGADO", 3, 7, "ORIGEN")), "ORIGEN", 4));
        assertEquals(4, valor("SELECT cantidad FROM inventario WHERE id=" + id));
        try (Connection con = DatabaseConnection.getConnection(); var st = con.createStatement()) {
            st.executeUpdate("DELETE FROM factura_detalle");
        }
        service.guardar(List.of(compra("LEGADO", 3, 7, "ORIGEN")), "ORIGEN", 4);
        assertEquals(3, valor("SELECT cantidad FROM inventario"));
        assertEquals(1, valor("SELECT COUNT(*) FROM inventario"));
        assertTrue(valor("SELECT inventario_id FROM factura_proveedor") > 0);
    }

    @Test
    @org.junit.jupiter.api.condition.EnabledIfSystemProperty(named = "ingreso.test.pg.url", matches = ".+")
    void ingresosConcurrentesNoPierdenIncrementos() throws Exception {
        int id = negativo("X", -10, 7);
        var ejecutor = java.util.concurrent.Executors.newFixedThreadPool(2);
        var inicio = new java.util.concurrent.CountDownLatch(1);
        try {
            var a = ejecutor.submit(() -> { inicio.await(); return service.guardar(List.of(compra("X", 3, 7, "C1")), null, 0); });
            var b = ejecutor.submit(() -> { inicio.await(); return service.guardar(List.of(compra("X", 4, 7, "C2")), null, 0); });
            inicio.countDown();
            a.get(20, java.util.concurrent.TimeUnit.SECONDS); b.get(20, java.util.concurrent.TimeUnit.SECONDS);
            assertEquals(-3, valor("SELECT cantidad FROM inventario WHERE id=" + id));
            assertEquals(2, valor("SELECT COUNT(*) FROM factura_proveedor"));
            assertEquals(1, valor("SELECT COUNT(*) FROM inventario"));
        } finally { ejecutor.shutdownNow(); }
    }
