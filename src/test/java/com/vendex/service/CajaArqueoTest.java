package com.vendex.service;

import com.vendex.config.DatabaseConnection;
import com.vendex.dao.CajaSesionDAOPostgres;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

/**
 * El esperado del arqueo debe restar egresos/retiros/ajustes igual que el neto
 * del resumen (antes sumaba todo en bruto).
 */
class CajaArqueoTest {

    private String dbName;
    private Connection con;

    @BeforeEach
    void setUp() throws Exception {
        dbName = "testdb_caja_" + UUID.randomUUID().toString().replace("-", "");
        con = DriverManager.getConnection("jdbc:hsqldb:mem:" + dbName, "sa", "");
        DatabaseConnection.setConnectionParams("jdbc:hsqldb:mem:" + dbName, "sa", "");
        try (Statement st = con.createStatement()) {
            st.execute("CREATE TABLE caja_sesion (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id INT, fecha_apertura TIMESTAMP, fecha_cierre TIMESTAMP, monto_inicial DECIMAL(12,2), monto_fisico DECIMAL(12,2), diferencia DECIMAL(12,2), estado VARCHAR(20), observaciones VARCHAR(500))");
            st.execute("CREATE TABLE caja_movimiento (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sesion_id INT, tipo VARCHAR(20), monto DECIMAL(12,2), descripcion VARCHAR(500), referencia_id INT, referencia_tipo VARCHAR(50), fecha TIMESTAMP, usuario_id INT)");
            st.execute("INSERT INTO caja_sesion(id, usuario_id, monto_inicial, estado) VALUES (1, 1, 100.00, 'ABIERTA')");
            st.execute("INSERT INTO caja_movimiento(sesion_id, tipo, monto, usuario_id) VALUES "
                    + "(1, 'INGRESO', 50.00, 1), (1, 'EGRESO', 20.00, 1), "
                    + "(1, 'RETIRO', 10.00, 1), (1, 'AJUSTE', 5.00, 1)");
        }
    }

    @AfterEach
    void tearDown() throws Exception {
        if (con != null && !con.isClosed()) con.close();
        DatabaseConnection.resetToDefault();
    }

    @Test
    void totalMovimientos_restaEgresosRetirosAjustes() {
        BigDecimal total = new CajaSesionDAOPostgres().calcularTotalMovimientos(1);
        assertEquals(0, total.compareTo(new BigDecimal("15.00")),
                "50 - 20 - 10 - 5 = 15, no 85");
    }

    @Test
    void esperado_cuadraConNetoDelResumen() {
        // esperado = inicial + movimientos firmados = 100 + 15 = 115
        BigDecimal esperado = new BigDecimal("100.00")
                .add(new CajaSesionDAOPostgres().calcularTotalMovimientos(1));
        assertEquals(0, esperado.compareTo(new BigDecimal("115.00")));
    }
}
